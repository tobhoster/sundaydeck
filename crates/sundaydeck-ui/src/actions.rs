use gpui::{App, KeyBinding, actions};

actions!(
    sundaydeck,
    [
        GoLive,
        NextLiveSlide,
        PrevLiveSlide,
        ToggleClearText,
        ToggleBlack,
        ToggleLogo,
        HardCutClearText,
        HardCutBlack,
        HardCutLogo,
        ToggleAudienceWindow,
        ToggleStageWindow,
        ToggleObsOverlay,
        ToggleDirectClickLive,
        ToggleQuickEdit,
        ClearStageMessage,
        NewService,
        NewSong,
        NewCustomSlide,
        ImportPastorPlan,
        OpenBiblesBundles,
        OpenBackgroundStudio,
        OpenAlertsTimers,
        OpenSettings,
        OpenWelcomeSetup,
        CheckForUpdates,
        SwitchTabSongs,
        SwitchTabBible,
        SwitchTabCustomSlides,
        SwitchTabThemes,
        ToggleLeftPane,
        ToggleRightPane,
        ToggleLibraryDrawer,
        ResetWorkspaceLayout,
        EditCut,
        EditCopy,
        EditPaste,
        EditSelectAll,
        OpenCheatSheetHelp,
        OpenStarterPacksHelp,
        OpenGithubIssues,
        DismissOverlay,
        CloseActiveWindow,
        QuitApp,
    ]
);

/// Context for live slide stepping: the Operator workspace, but never while a text field inside it
/// has focus (bindings dispatch before the field's own key handler, so Space/arrows would step).
const SLIDE_STEP_CONTEXT: &str = "OperatorWorkspace && !TextInput";

/// Registers global recovery hotkeys, desktop menu shortcuts, layout toggles, and navigation.
/// Recovery overrides (`F1`-`F3`) stay active globally (`Shift+F1`-`F3` perform instant hard cuts);
/// slide stepping is scoped to `OperatorWorkspace` so typing into text fields never advances slides.
pub fn register_keybindings(cx: &mut App) {
    cx.bind_keys([
        KeyBinding::new("f1", ToggleClearText, None),
        KeyBinding::new("f2", ToggleBlack, None),
        KeyBinding::new("f3", ToggleLogo, None),
        KeyBinding::new("shift-f1", HardCutClearText, None),
        KeyBinding::new("shift-f2", HardCutBlack, None),
        KeyBinding::new("shift-f3", HardCutLogo, None),
        KeyBinding::new("f5", GoLive, None),
        KeyBinding::new("cmd-enter", GoLive, None),
        KeyBinding::new("ctrl-enter", GoLive, None),
        KeyBinding::new("right", NextLiveSlide, Some(SLIDE_STEP_CONTEXT)),
        KeyBinding::new("down", NextLiveSlide, Some(SLIDE_STEP_CONTEXT)),
        KeyBinding::new("pagedown", NextLiveSlide, Some(SLIDE_STEP_CONTEXT)),
        KeyBinding::new("space", NextLiveSlide, Some(SLIDE_STEP_CONTEXT)),
        KeyBinding::new("left", PrevLiveSlide, Some(SLIDE_STEP_CONTEXT)),
        KeyBinding::new("up", PrevLiveSlide, Some(SLIDE_STEP_CONTEXT)),
        KeyBinding::new("pageup", PrevLiveSlide, Some(SLIDE_STEP_CONTEXT)),
        KeyBinding::new("cmd-e", ToggleQuickEdit, Some("OperatorWorkspace")),
        KeyBinding::new("ctrl-e", ToggleQuickEdit, Some("OperatorWorkspace")),
        KeyBinding::new("cmd-n", NewService, Some("OperatorWorkspace")),
        KeyBinding::new("ctrl-n", NewService, Some("OperatorWorkspace")),
        KeyBinding::new("cmd-shift-n", NewSong, Some("OperatorWorkspace")),
        KeyBinding::new("ctrl-shift-n", NewSong, Some("OperatorWorkspace")),
        KeyBinding::new("cmd-,", OpenSettings, Some("OperatorWorkspace")),
        KeyBinding::new("ctrl-,", OpenSettings, Some("OperatorWorkspace")),
        KeyBinding::new("cmd-shift-a", ToggleAudienceWindow, None),
        KeyBinding::new("ctrl-shift-a", ToggleAudienceWindow, None),
        KeyBinding::new("cmd-shift-s", ToggleStageWindow, None),
        KeyBinding::new("ctrl-shift-s", ToggleStageWindow, None),
        KeyBinding::new("cmd-b", ToggleLeftPane, Some("OperatorWorkspace")),
        KeyBinding::new("ctrl-b", ToggleLeftPane, Some("OperatorWorkspace")),
        KeyBinding::new("cmd-alt-b", ToggleRightPane, Some("OperatorWorkspace")),
        KeyBinding::new("ctrl-alt-b", ToggleRightPane, Some("OperatorWorkspace")),
        KeyBinding::new("cmd-j", ToggleLibraryDrawer, Some("OperatorWorkspace")),
        KeyBinding::new("ctrl-j", ToggleLibraryDrawer, Some("OperatorWorkspace")),
        KeyBinding::new(
            "cmd-shift-0",
            ResetWorkspaceLayout,
            Some("OperatorWorkspace"),
        ),
        KeyBinding::new(
            "ctrl-shift-0",
            ResetWorkspaceLayout,
            Some("OperatorWorkspace"),
        ),
        KeyBinding::new("cmd-1", SwitchTabSongs, Some("OperatorWorkspace")),
        KeyBinding::new("ctrl-1", SwitchTabSongs, Some("OperatorWorkspace")),
        KeyBinding::new("cmd-2", SwitchTabBible, Some("OperatorWorkspace")),
        KeyBinding::new("ctrl-2", SwitchTabBible, Some("OperatorWorkspace")),
        KeyBinding::new("cmd-3", SwitchTabCustomSlides, Some("OperatorWorkspace")),
        KeyBinding::new("ctrl-3", SwitchTabCustomSlides, Some("OperatorWorkspace")),
        KeyBinding::new("cmd-4", SwitchTabThemes, Some("OperatorWorkspace")),
        KeyBinding::new("ctrl-4", SwitchTabThemes, Some("OperatorWorkspace")),
        KeyBinding::new("cmd-x", EditCut, Some("TextInput")),
        KeyBinding::new("ctrl-x", EditCut, Some("TextInput")),
        KeyBinding::new("cmd-c", EditCopy, Some("TextInput")),
        KeyBinding::new("ctrl-c", EditCopy, Some("TextInput")),
        KeyBinding::new("cmd-v", EditPaste, Some("TextInput")),
        KeyBinding::new("ctrl-v", EditPaste, Some("TextInput")),
        KeyBinding::new("cmd-a", EditSelectAll, Some("TextInput")),
        KeyBinding::new("ctrl-a", EditSelectAll, Some("TextInput")),
        KeyBinding::new("escape", DismissOverlay, Some("OperatorWorkspace")),
        KeyBinding::new("cmd-w", CloseActiveWindow, None),
        KeyBinding::new("ctrl-w", CloseActiveWindow, None),
        KeyBinding::new("cmd-q", QuitApp, None),
        KeyBinding::new("ctrl-q", QuitApp, None),
    ]);
}
